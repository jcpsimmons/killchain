"""Generate the `contracts/` stub package and contract tests from a Contract.

The frontier model builds against `contracts.<module>.<function>` and never
sees an implementation. In HARNESS_MODE=stub the functions answer from
synthetic fixtures. In HARNESS_MODE=real they delegate to
`private_impl.<module>`, which lives outside the public tree and is written
by the local model.
"""
from __future__ import annotations

import json
from pathlib import Path

from killchain.contract import Contract, Interface


def write_private_fixtures(c: Contract, path: Path) -> None:
    """Real examples, written only into the private run dir."""
    path.write_text(json.dumps(c.private_fixtures_dict(), indent=2, sort_keys=True))

RUNTIME = '''"""GENERATED by harness. Do not edit. Edit the contract instead."""
import importlib
import json
import os
import pathlib

_FIXTURES = json.loads((pathlib.Path(__file__).parent / "_fixtures.json").read_text())


def mode() -> str:
    return os.environ.get("HARNESS_MODE", "stub")


def _norm(obj):
    return json.loads(json.dumps(obj, sort_keys=True, default=str))


def call(module: str, function: str, kwargs: dict):
    if mode() == "stub":
        fixtures = _FIXTURES[module][function]
        want = _norm(kwargs)
        for fx in fixtures:
            if _norm(fx["inputs"]) == want:
                return fx["output"]
        return fixtures[0]["output"]
    impl = importlib.import_module(f"private_impl.{module}")
    return getattr(impl, function)(**kwargs)
'''

TEST_SRC = '''"""GENERATED by harness: contract conformance tests.

Stub mode: replays the PUBLIC decoy fixtures through the stubs (sanity).
Real mode: HARNESS_FIXTURES points at the private fixtures file; passing
proves the private implementation honours the contract the public half was
built against. Those real examples never enter this directory.
"""
import importlib
import json
import os
import pathlib
import unittest


def _load():
    if os.environ.get("HARNESS_MODE", "stub") == "real":
        p = os.environ.get("HARNESS_FIXTURES")
        if not p:
            raise RuntimeError("HARNESS_MODE=real needs HARNESS_FIXTURES=<private fixtures json>")
        return json.loads(pathlib.Path(p).read_text())
    here = pathlib.Path(__file__).resolve().parent.parent
    return json.loads((here / "contracts" / "_fixtures.json").read_text())


def _norm(o):
    return json.loads(json.dumps(o, sort_keys=True, default=str))


class ContractConformance(unittest.TestCase):
    def test_fixtures(self):
        n = 0
        for module, funcs in _load().items():
            mod = importlib.import_module(f"contracts.{module}")
            for fn, cases in funcs.items():
                for k, case in enumerate(cases):
                    with self.subTest(f"{module}.{fn}[{k}]"):
                        got = getattr(mod, fn)(**case["inputs"])
                        self.assertEqual(_norm(got), _norm(case["output"]))
                    n += 1
        self.assertGreater(n, 0, "no fixtures loaded")


if __name__ == "__main__":
    unittest.main()
'''


def _sig(i: Interface) -> str:
    return ", ".join(f"{p.name}: {p.type}" for p in i.params)


def _kwargs(i: Interface) -> str:
    return "{" + ", ".join(f'"{p.name}": {p.name}' for p in i.params) + "}"


def _module_src(i_list: list[Interface], module: str) -> str:
    out = ['"""GENERATED by harness from the contract. Do not edit."""',
           "from contracts._runtime import call", ""]
    for i in i_list:
        out.append(f"\ndef {i.function}({_sig(i)}) -> {i.returns}:")
        doc = [i.description.strip() or i.function, ""]
        if i.params:
            doc.append("Args:")
            for p in i.params:
                doc.append(f"    {p.name} ({p.type}): {p.description}".rstrip())
        doc.append(f"Returns: {i.returns}")
        out.append('    """' + "\n    ".join(doc) + '\n    """')
        out.append(f'    return call("{module}", "{i.function}", {_kwargs(i)})')
        out.append("")
    return "\n".join(out)


def generate(c: Contract, public_dir: Path) -> list[Path]:
    """Write contracts/ and tests/test_contracts.py into public_dir."""
    written: list[Path] = []
    pkg = public_dir / "contracts"
    pkg.mkdir(parents=True, exist_ok=True)
    by_module: dict[str, list[Interface]] = {}
    for i in c.interfaces:
        by_module.setdefault(i.module, []).append(i)

    (pkg / "__init__.py").write_text(
        '"""GENERATED by harness. Private-side interfaces. Do not edit."""\n'
        + "".join(f"from . import {m}\n" for m in sorted(by_module))
        + f"__all__ = {sorted(by_module)!r}\n")
    written.append(pkg / "__init__.py")
    (pkg / "_runtime.py").write_text(RUNTIME)
    written.append(pkg / "_runtime.py")
    fixtures = {m: {i.function: [{"inputs": f.inputs, "output": f.output} for f in i.fixtures]
                    for i in lst} for m, lst in by_module.items()}
    (pkg / "_fixtures.json").write_text(json.dumps(fixtures, indent=2, sort_keys=True))
    written.append(pkg / "_fixtures.json")
    for m, lst in by_module.items():
        (pkg / f"{m}.py").write_text(_module_src(lst, m))
        written.append(pkg / f"{m}.py")

    tests = public_dir / "tests"
    tests.mkdir(exist_ok=True)
    (tests / "__init__.py").touch()
    (tests / "test_contracts.py").write_text(TEST_SRC)
    written.append(tests / "test_contracts.py")
    return written
